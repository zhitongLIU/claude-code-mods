#!/usr/bin/env bash
# Copies the shared code at the repo root into each mod that ships it. A mod is installed from its own folder
# only, and its hooks may import nothing outside it, so each mod carries a generated copy.
#
#   scripts/sync-shared.sh          write the copies
#   scripts/sync-shared.sh --check  exit 1 when a copy differs from shared/ (run before committing, and in CI)
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
mods=(mission-control plan-control)
# shared/<name> → mods/<mod>/hooks/<name>
shared=(mux)

check=0
[[ "${1:-}" == "--check" ]] && check=1

# Writes the generated copy of shared/$1 into the folder $2.
render() {
  local name="$1" out="$2" f
  mkdir -p "$out"
  for f in "$root/shared/$name"/*.ts; do
    {
      printf '// Generated by scripts/sync-shared.sh from shared/%s/%s: do not edit here.\n' "$name" "$(basename "$f")"
      printf '// Edit shared/%s/ and run scripts/sync-shared.sh.\n' "$name"
      cat "$f"
    } >"$out/$(basename "$f")"
  done
}

status=0
for name in "${shared[@]}"; do
  for mod in "${mods[@]}"; do
    dest="$root/mods/$mod/hooks/$name"
    if ((check)); then
      tmp="$(mktemp -d)"
      render "$name" "$tmp"
      if ! diff -r "$tmp" "$dest" >/dev/null 2>&1; then
        echo "drift: mods/$mod/hooks/$name differs from shared/$name. Run scripts/sync-shared.sh." >&2
        diff -ru "$tmp" "$dest" >&2 || true
        status=1
      fi
      rm -rf "$tmp"
    else
      rm -rf "$dest"
      render "$name" "$dest"
      echo "synced shared/$name → mods/$mod/hooks/$name"
    fi
  done
done
exit "$status"
